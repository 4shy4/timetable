/** 某个节日用哪个图案（可能返回兜底） */
export function motifFor(festivalKey) {
  const id = BY_FESTIVAL[festivalKey];
  return MOTIFS[id] || FALLBACK;
}

/**
 * 画这个节日泡泡要用的**图案规格**。
 *
 * @param {string} festivalKey
 * @param {object} [opts]
 * @param {object} [opts.customArt] `settings.festivalArt`（节日 key → 图片 data URL）
 * @returns {{id:string, label:string, custom:boolean, shapes:Array, image:string|null}}
 *          `custom: true` 时 `image` 是用户自己那张图的 data URL（形状清单就不用了）
 */
export function festivalArt(festivalKey, { customArt = null } = {}) {
  const custom = customArt && typeof customArt === 'object' ? customArt[festivalKey] : null;
  if (typeof custom === 'string' && custom.startsWith('data:image/')) {
    return { id: 'custom', label: '自定义图片', custom: true, shapes: [], image: custom };
  }
  const m = motifFor(festivalKey);
  return {
    id: BY_FESTIVAL[festivalKey] || 'fallback',
    label: m.label,
    custom: false,
    shapes: m.shapes,
    image: null,
  };
}

/** 所有图案（设置页要列出来给人挑；也方便测试逐个检查形状合法） */
export function allMotifs() {
  return Object.entries(MOTIFS).map(([id, m]) => ({ id, label: m.label, shapes: m.shapes }));
}

