//
// 用户第 46 轮问"能不能去网上搜节日图片"，第 47 轮定了 **A+C**：
//   A. 默认用**自己画的矢量图案**（不引入任何有版权的图；公开 demo 是 MIT 仓库，不能塞别人的图）
//   C. 允许用户**给某个节日换自己的图**（在设置里选一张本地图片，压到 256×256 存进设置里）
//
// ⚠️ 为什么是"矢量**规格**"而不是 SVG 字符串 / 位图：
//   · 三端要共用同一份图案：网页是 canvas、Windows 那层是 WPF。WPF **不认识 SVG**，
//     而 base64 位图又要在这里做编码器 —— 所以 core 只给**形状清单**，
//     各端用它自己那套原语画（canvas 的 arc、WPF 的 Ellipse/Polygon）。
//     这就是这个项目那条线：**core 说画什么，原生只负责画。**
//   · 形状只用四种：`c` 圆 / `e` 椭圆 / `l` 折线（描边）/ `p` 多边形（填色）。
//     够画月亮、灯笼、粽子、雪花、旗子…（折线是后来补的：灯笼的金带、雪花的三根轴
//     最早拿两个点当多边形 fill，画出来只是一条看不见的细缝。）
//
// ⚠️ 图案是画在**节日红**泡泡上的（`FESTIVAL_COLORS.fill` #e03a3a），所以**主图案一律用
//    金/白/亮黄这类高对比色**：红底上再画红等于没画（第 46 轮那版"春节鞭炮"就是这么废的）。
//    红只能当极小面积的暗部（齿轮的中孔、龙的眼睛那种）。这条规则有测试兜着
//    （tools/festival-art.test.mjs 的"不跟自己的底色同色"）。
//
// 坐标系：**100×100 的方框**，原点左上；调用方把它按泡泡半径缩放、再裁成圆形。

/** 形状缩写（省地方，也让 native 那侧的 switch 只有四个分支） */
const c = (x, y, r, color, a = 1) => ({ t: 'c', x, y, r, color, a });
const e = (x, y, rx, ry, color, a = 1, rot = 0) => ({ t: 'e', x, y, rx, ry, color, a, rot });
/**
 * `p` = 多边形（**填色**），`l` = 折线（**描边**）。
 *
 * ⚠️ 这两者混用会出很难发现的错：拿两个点当多边形去 fill，画出来是一条几乎看不见的细缝
 *    （灯笼的金色横带、柳枝、雪花的三根轴最早就是这么没的）。
 *    所以这里**按点数自动分流**：正好 2 个点 = 一根线，3 个以上 = 一块面。
 */
const LINE_W = 3.6;   // 线宽（同样是 100 框里的单位，随泡泡缩放）
const ln = (pts, color, a = 1, w = LINE_W) => ({ t: 'l', pts, color, a, w });
const p = (pts, color, a = 1) => (pts.length === 2
  ? ln(pts, color, a)
  : { t: 'p', pts, color, a });


